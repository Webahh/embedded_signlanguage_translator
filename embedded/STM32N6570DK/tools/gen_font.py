def generate_header(font_data, output_path):
    chars = sorted(font_data.keys())
    min_ascii = min(ord(c) for c in chars)
    max_ascii = max(ord(c) for c in chars)
    num_chars = max_ascii - min_ascii + 1

    with open(output_path, 'w') as f:
        f.write("#ifndef FONT_8X16_H\n")
        f.write("#define FONT_8X16_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("#define FONT_8X16_WIDTH  8\n")
        f.write("#define FONT_8X16_HEIGHT 16\n")
        f.write("#define FONT_8X16_FIRST_CHAR 0x20\n")
        f.write(f"#define FONT_8X16_LAST_CHAR  0x{max_ascii:02X}\n")
        f.write(f"\n")
        f.write(f"static const uint8_t font_8x16[{num_chars}][16] = {{\n")

        for code in range(min_ascii, max_ascii + 1):
            c = chr(code)
            if c in font_data:
                bytes_list = font_data[c]
            else:
                bytes_list = [0] * 16
            hex_str = ", ".join(f"0x{b:02X}" for b in bytes_list)
            comment = f"/* '{c}' (0x{code:02X}) */" if c.isprintable() else f"/* 0x{code:02X} */"
            f.write(f"    {{ {hex_str} }}, {comment}\n")

        f.write("};\n\n")
        f.write("#endif /* FONT_8X16_H */\n")

    print(f"Generated {output_path}")
    print(f"  ASCII range: 0x{min_ascii:02X} - 0x{max_ascii:02X}")
    print(f"  Total characters: {num_chars}")
    print(f"  Total font data: {num_chars * 16} bytes")

